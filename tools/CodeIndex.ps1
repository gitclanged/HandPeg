# Writes CODE_INDEX.md's generated part: every source file with its types, its "// ----- ... -----" sections and its
# members (C#), or its named elements (XAML), each with the lines it spans, so a fix can read one window of a file
# instead of the whole of it. The hand-written part of the index (above the marker line) is kept as it is.
#
#   pwsh -NoProfile -File tools\CodeIndex.ps1 [-Index ..\CODE_INDEX.md]
#
# Run it after a pass that adds or moves a good deal of code. Lines are 1-based; a member's range starts at its doc
# comment and ends before the next member's.
param([string]$Index = (Join-Path $PSScriptRoot '..\..\CODE_INDEX.md'))

$ErrorActionPreference = 'Stop'
$root = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
$marker = '<!-- Generated by HandPegApp/tools/CodeIndex.ps1: everything below this line is replaced when it runs. -->'

$typeRx = [regex]'^\s*(?:\[[^\]]*\]\s*)*(?:(?:public|internal|private|protected|static|sealed|abstract|partial|readonly|file)\s+)*(?:record\s+(?:struct|class)\s+|(class|struct|record|enum|interface)\s+)(\w+)'
$memberRx = [regex]'^(\s+)(?:\[[^\]]*\]\s*)*(?:(?:public|private|protected|internal|static|override|virtual|async|sealed|new|unsafe|partial|abstract)\s+)+(?:\([^()]*\)(?:\[\])?\??\s+|[\w<>\[\],.?]+(?:\s*<[^=]*?>)?\??\s+)?(\w+)\s*(?:<[^>()]*>)?\s*\('
$sectionRx = [regex]'^\s*//\s*-----\s*(.+?)\s*-----\s*$'

function Members([string]$path) {
    $lines = [System.IO.File]::ReadAllLines($path)
    $items = [System.Collections.Generic.List[object]]::new()
    for ($i = 0; $i -lt $lines.Length; $i++) {
        $line = $lines[$i]
        if (($m = $sectionRx.Match($line)).Success) {
            $items.Add([pscustomobject]@{ Kind = 'section'; Name = $m.Groups[1].Value; Start = $i + 1; Line = $i + 1 }); continue
        }
        if (($t = $typeRx.Match($line)).Success -and $line -notmatch '^\s*//' -and $line -notmatch '\bnew\s') {
            $kind = if ($t.Groups[1].Success) { $t.Groups[1].Value } else { 'record' }
            $indent = $line.Length - $line.TrimStart().Length
            $close = $lines.Length
            for ($j = $i + 1; $j -lt $lines.Length; $j++) { if ($lines[$j] -match "^\s{$indent}\}") { $close = $j + 1; break } }
            if ($line.TrimEnd().EndsWith(';')) { $close = $i + 1 }
            $items.Add([pscustomobject]@{ Kind = $kind; Name = $t.Groups[2].Value; Start = (DocStart $lines $i); Line = $i + 1; Close = $close }); continue
        }
        $m = $memberRx.Match($line)
        if (-not $m.Success -or $line -match '^\s*//' -or ($line.TrimEnd().EndsWith(';') -and $line -notmatch '=>')) { continue }
        $before = $line.Substring(0, $line.IndexOf('('))
        if ($before -match '=' -or $before -match '\b(event|delegate|const|extern)\b' -or $line -match '\bextern\b') { continue }
        $name = $m.Groups[2].Value
        if ($name -in 'if', 'for', 'foreach', 'while', 'switch', 'using', 'lock', 'return', 'new', 'nameof', 'typeof', 'catch', 'public', 'private', 'protected', 'internal', 'static', 'override', 'virtual', 'async', 'sealed', 'unsafe', 'partial', 'abstract', 'readonly', 'const', 'event') { continue }
        $items.Add([pscustomobject]@{ Kind = 'member'; Name = $name; Start = (DocStart $lines $i); Line = $i + 1 })
    }

    # Each runs to the line before the next one starts (its doc comment included), less blank lines.
    for ($k = 0; $k -lt $items.Count; $k++) {
        $end = if ($k + 1 -lt $items.Count) { $items[$k + 1].Start - 1 } else { $lines.Length }
        while ($end -gt $items[$k].Line -and $lines[$end - 1].Trim() -in '', '}') { $end-- }
        if ($items[$k].PSObject.Properties['Close']) { $end = $items[$k].Close }
        $items[$k] | Add-Member End $end
    }
    [pscustomobject]@{ Lines = $lines.Length; Items = $items }
}

# Where a declaration's doc comment (and attributes) begin, above it.
function DocStart($lines, [int]$i) {
    $s = $i
    while ($s -gt 0 -and $lines[$s - 1].TrimStart() -match '^(///|\[)') { $s-- }
    $s + 1
}

function Xaml([string]$path) {
    $lines = [System.IO.File]::ReadAllLines($path)
    $out = [System.Collections.Generic.List[string]]::new()
    $open = -1
    for ($i = 0; $i -lt $lines.Length; $i++) {
        $line = $lines[$i]
        if ($line -match '^\s*<[\w:.]') { $open = $i }
        if ($line -match 'x:Name="(\w+)"' -and $open -ge 0 -and $lines[$open] -match '^(\s*)<([\w:.]+)') {
            $name = ([regex]::Match($line, 'x:Name="(\w+)"')).Groups[1].Value
            $indent = $Matches[1].Length; $type = $Matches[2]

            # The tag ends on the first line ending in ">": there, "/>" closes it; otherwise it runs to its closing tag.
            $end = $open + 1
            for ($j = $i; $j -lt $lines.Length; $j++) {
                if ($lines[$j] -match '/>\s*$') { $end = $j + 1; break }
                if ($lines[$j] -match '>\s*$') {
                    for ($k = $j + 1; $k -lt $lines.Length; $k++) { if ($lines[$k] -match "^\s{$indent}</") { $end = $k + 1; break } }
                    break
                }
            }
            $range = if ($end -gt $open + 1) { "L$($open + 1)-$end" } else { "L$($open + 1)" }
            $out.Add("- $range ``$name`` ($type)")
        }
        elseif ($line -match 'Style="\{StaticResource SectionTitle\}"' -and $line -match 'Text="([^"]+)"') {
            $out.Add("- L$($i + 1) § $([System.Net.WebUtility]::HtmlDecode($Matches[1]))")
        }
        elseif ($line -match '^\s*<TabItem\b[^>]*Header="([^"]+)"') {
            $out.Add("- L$($i + 1) tab ""$([System.Net.WebUtility]::HtmlDecode($Matches[1]))""")
        }
    }
    [pscustomobject]@{ Lines = $lines.Length; Items = $out }
}

# The body: one block per file, in groups; the table of contents (each file's line in this index) is put above it.
$body = [System.Collections.Generic.List[string]]::new()
$toc = [System.Collections.Generic.List[object]]::new()
$src = Join-Path $root 'src'
$groups = [ordered]@{
    'src/ (entry point, app, main window)' = { param($f) $f.DirectoryName -eq $src }
    'src/Controls/' = { param($f) $f.DirectoryName -eq "$src\Controls" }
    'src/Dialogs/' = { param($f) $f.DirectoryName -eq "$src\Dialogs" }
    'src/Docking/' = { param($f) $f.DirectoryName -eq "$src\Docking" }
    'src/Views/' = { param($f) $f.DirectoryName -eq "$src\Views" }
    'src/ViewModels/' = { param($f) $f.DirectoryName -eq "$src\ViewModels" }
    'src/Services/' = { param($f) $f.DirectoryName -eq "$src\Services" }
    'src/Models/' = { param($f) $f.DirectoryName -eq "$src\Models" -or $f.DirectoryName -like "$src\Models\*" }
}
$files = Get-ChildItem $src -Recurse -Include *.cs, *.xaml | Where-Object { $_.FullName -notmatch '[\\/](obj|bin)[\\/]' -and $_.Name -ne 'AssemblyInfo.cs' } | Sort-Object FullName
foreach ($group in $groups.Keys) {
    $body.Add(''); $body.Add("### $group")
    foreach ($file in $files | Where-Object { & $groups[$group] $_ }) {
        $rel = $file.FullName.Substring($root.Length + 1).Replace('\', '/')
        $body.Add('')
        $toc.Add([pscustomobject]@{ File = $rel; At = $body.Count })
        if ($file.Extension -eq '.xaml') {
            $x = Xaml $file.FullName
            $body.Add("#### $rel ($($x.Lines) lines)")
            foreach ($item in $x.Items) { $body.Add($item) }
        }
        else {
            $c = Members $file.FullName
            $body.Add("#### $rel ($($c.Lines) lines)")
            foreach ($item in $c.Items) {
                $range = if ($item.End -gt $item.Start) { "L$($item.Start)-$($item.End)" } else { "L$($item.Start)" }
                $text = switch ($item.Kind) {
                    'section' { "§ $($item.Name)" }
                    'member' { $item.Name }
                    default { "$($item.Kind) **$($item.Name)**" }
                }
                $body.Add("- $range $text")
            }
        }
        $toc[$toc.Count - 1] | Add-Member Lines ($body.Count - $toc[$toc.Count - 1].At)
    }
}

$head = if (Test-Path $Index) { $existing = [System.IO.File]::ReadAllText($Index).Replace("`r`n", "`n"); $at = $existing.IndexOf($marker); if ($at -ge 0) { $existing.Substring(0, $at) } else { $existing.TrimEnd() + "`n`n" } } else { "# HandPeg code index`n`n" }
$intro = @(
    $marker, '',
    "## Generated index ($(Get-Date -Format 'yyyy-MM-dd'))", '',
    'Per file: `L<start>-<end>` then the type (class, record, enum...), `§` a `// -----` section, or a member (methods and',
    'constructors; properties and fields are not listed). XAML: named elements, Settings sections (`§`) and tabs.', '',
    '### Where each file is in this index', '',
    'Read only a file''s block: `offset` = its line here, `limit` = its length.', '')
$headLines = ($head -split "`n").Count - 1
$first = $headLines + $intro.Count + $toc.Count + 1
$tocLines = foreach ($entry in $toc) { "- ``$($entry.File)``: line $($first + $entry.At), $($entry.Lines) lines" }
$all = $head + (($intro + $tocLines + $body) -join "`n") + "`n"
[System.IO.File]::WriteAllText($Index, $all)
"Wrote $Index ($((Get-Item $Index).Length) bytes, $(($all -split "`n").Count) lines)"
